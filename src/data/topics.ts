import type { Topic, Level } from "@/lib/types";
type Row = [string, string, string, string, string, string];
function topic(
  id: string,
  title: string,
  description: string,
  level: Level,
  icon: string,
  color: string,
  rows: Row[],
): Topic {
  return {
    id,
    title,
    description,
    level,
    icon,
    color,
    dialogs: rows.map(
      (
        [question, translation, answer, alternative, explanation, chunked],
        i,
      ) => ({
        id: `${id}-${i + 1}`,
        question,
        translation,
        answer,
        alternatives: [alternative],
        explanation,
        chunks: chunked.split("|"),
      }),
    ),
  };
}
